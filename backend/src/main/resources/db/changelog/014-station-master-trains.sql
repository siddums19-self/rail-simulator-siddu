-- Real trains that pass each Station Master station, with the approach line they arrive on and the
-- line they leave by. The game rotates through them (no repeats until all have run), at the
-- station's traffic flow. Edit / add rows to change a station's traffic.
CREATE TABLE sm_station_trains (
    id           BIGSERIAL PRIMARY KEY,
    station_code VARCHAR(8)  NOT NULL,
    train_no     VARCHAR(8)  NOT NULL,
    train_name   VARCHAR(80) NOT NULL,
    kind         VARCHAR(10) NOT NULL,   -- exp | vip | pass | goods
    from_line    VARCHAR(8)  NOT NULL,
    to_line      VARCHAR(8)  NOT NULL,
    reverses     BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_sm_station_trains_station ON sm_station_trains(station_code);
